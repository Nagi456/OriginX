"""List the game symbols (MSVC-mangled names) written as string literals in client/ and write
client/GameSymbolList.inc, one C string per line. The signature dump (client/SignatureDump.cpp) resolves
each of them in the running game and writes the bytes at its address, so MyClient can later find the
same functions in game versions LeviLamina does not cover yet."""
import argparse
from pathlib import Path
import re

REPO = Path(__file__).resolve().parent.parent
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
GAP = re.compile(r'\s*(?:\\\n\s*)?')  # whitespace (and macro line continuations) between joined literals


def joined_literals(text):
    """Every run of adjacent string literals ("a" "b" -> "ab"), outside comments."""
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    pos = 0
    while True:
        m = LITERAL.search(text, pos)
        if not m:
            return out
        value = m.group(1)
        end = m.end()
        while True:
            gap = GAP.match(text, end)
            nxt = LITERAL.match(text, gap.end()) if gap else None
            if not nxt:
                break
            value += nxt.group(1)
            end = nxt.end()
        out.append(value)
        pos = end


def game_symbols(texts):
    names = set()
    for text in texts:
        for value in joined_literals(text):
            if value.startswith("?") and "@@" in value and "\\" not in value and " " not in value:
                names.add(value)
    return sorted(names)


def write(output, names):
    body = "// Generated by tools/list_game_symbols.py; do not edit.\n" + "".join('"' + n + '",\n' for n in names)
    if not output.exists() or output.read_text() != body:
        output.write_text(body)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=REPO / "client/GameSymbolList.inc")
    args = parser.parse_args(argv)
    sources = sorted(p for p in (REPO / "client").iterdir() if p.suffix in (".cpp", ".h"))
    names = game_symbols(p.read_text(encoding="utf-8", errors="replace") for p in sources)
    write(args.output, names)
    print(f"{len(names)} game symbols -> {args.output}")


if __name__ == "__main__":
    main()
