"""Regenerate MarksGlyph.h from the OriginX logo (requires Pillow)."""
from io import BytesIO
from pathlib import Path

from PIL import Image

source = Path(__file__).resolve().parents[1]
# The client's own logo (assets/logo-mark.png), high resolution (user decision 2026-11-18). The page is 1024x1024,
# so each of the 16x16 cells is 64x64 and the game draws the mark that much finer than a 16x16 cell. The logo fills a
# 44x44 box in rows 14-57 of its cell, the same share of the cell as the old 10x10 mark in rows 4-13, so it stays
# about as tall as the letters (r57-test55: a mark filling the cell was taller than the name).
CELL = 64
BOX = 44
page = Image.new("RGBA", (16 * CELL, 16 * CELL))
logo = Image.open(source / "assets" / "logo-mark.png").convert("RGBA")
logo = logo.crop(logo.getbbox())
scale = BOX / max(logo.size)
logo = logo.resize((max(1, round(logo.width * scale)), max(1, round(logo.height * scale))), Image.LANCZOS)
x0 = 2 + (BOX - logo.width) // 2
y0 = 15 * CELL + 14 + (BOX - logo.height) // 2
page.alpha_composite(logo, (x0, y0))

png = BytesIO()
page.save(png, format="PNG")
data = png.getvalue()
lines = ["    " + ", ".join(map(str, data[i:i + 16])) + "," for i in range(0, len(data), 16)]
(source / "MarksGlyph.h").write_text(
    "#pragma once\n// Generated by tools/make_marks_glyph.py.\n"
    "inline constexpr unsigned char MarksGlyph[] = {\n" + "\n".join(lines) + "\n};\n",
    encoding="ascii",
)
